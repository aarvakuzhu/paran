# First run with templates, against the strict fake Google (tests/fake_google.py).
import asyncio, sys, json, re, os
import os; SP = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, SP)
src = open(os.path.join(SP, 'access_e2e.py')).read()
exec(src.split('\nasync def main():')[0].replace("import os; SP = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, SP)", ""))
G.FILES.clear(); G.SHEETS.clear(); G.PICKED.clear()
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        # ---- a group template
        a, A, errs = await phone(b, OWNER)
        await A.click('#create'); await A.wait_for_timeout(300)
        check('What are you setting up?' in T(await A.inner_text('body')), 'templates shown on first start')
        await A.screenshot(path=f'{SP}/p1-pick.png')
        await A.click('[data-tpl="group"]'); await A.wait_for_timeout(300)
        await A.screenshot(path=f'{SP}/p2-edit.png', full_page=True)
        # edit: remove Classrooms place, remove "Shelf 2", add a room, rename the storage unit, add an inventory
        await A.click('[data-rmplace="0:2"]'); await A.wait_for_timeout(100)
        await A.click('[data-rmroom="1:0:1"]'); await A.wait_for_timeout(100)
        await A.click('[data-addroom="0:0"]'); await A.wait_for_timeout(300); await A.fill('.sheet input', 'Costume racks'); await A.click('.sheet button.primary'); await A.wait_for_timeout(300)
        await A.fill('[data-iname="1"]', 'Self storage'); await A.wait_for_timeout(100)
        await A.click('[data-addinv]'); await A.wait_for_timeout(300); await A.fill('.sheet input', 'Volunteer garage'); await A.click('.sheet button.primary'); await A.wait_for_timeout(300)
        await A.click('[data-create]'); await A.wait_for_timeout(300)
        check(bool(await A.query_selector('[data-gname]:focus')), 'group name is asked for before creating')
        await A.fill('[data-gname]', 'Tamil School')
        await A.click('[data-create]'); await A.wait_for_timeout(9000)
        print(G.tree(OWNER))
        names = lambda sid: sorted(r['name'] for r in G.rows(sid, 'Locations'))
        sheet = lambda n: next(f['id'] for f in G.FILES.values() if f['name'] == n and f['mime'] == G.SHEET)
        mb, ss, vg = sheet('Main building'), sheet('Self storage'), sheet('Volunteer garage')
        check(names(mb) == sorted(['Hall or stage', 'Stage closet', 'AV cabinet', 'Costume racks', 'Office', 'Supply cabinet', 'Kitchen', 'Pantry']), f'Main building places as edited ({names(mb)})')
        check(names(ss) == sorted(['Shelves', 'Shelf 1', 'Bins on the floor']), f'storage unit places as edited ({names(ss)})')
        check(names(vg) == [], 'added inventory created empty')
        gf = next(f for f in G.FILES.values() if f['app'].get('stash') == 'group')
        check(gf['name'] == 'Tamil School' and all(G.FILES[G.FILES[s]['parents'][0]]['parents'] == [gf['id']] for s in (mb, ss, vg)), 'all three inventories inside the group folder')
        d = next(f['id'] for f in G.FILES.values() if f['app'].get('stash') == 'directory')
        check(sorted(r['name'] for r in G.rows(d, 'Inventories')) == ['Main building', 'Self storage', 'Volunteer garage'], 'group directory lists them')
        rooms = [r for r in G.rows(mb, 'Locations') if r['name'] == 'Costume racks']
        top = [r for r in G.rows(mb, 'Locations') if r['name'] == 'Hall or stage']
        check(rooms and top and rooms[0]['parentId'] == top[0]['id'] and top[0]['kind'] == 'place', 'rooms sit inside their place')
        for f in G.FILES.values():
            if f['owner'] == OWNER: print('   ', f['id'], f['name'], f['parents'], f['app'].get('stash'))
        page = T(await A.inner_text('body')); print('  url', A.url, 'page:', page[:300])
        check('Hall or stage' in page, 'lands on Places with them')
        await A.reload(); await A.wait_for_timeout(3000)
        print('  after reload:', T(await A.inner_text('body'))[:160])
        await A.screenshot(path=f'{SP}/p3-places.png', full_page=True)
        await a.close()
        # ---- home template, untouched; and Back works
        h, H, herr = await phone(b, 'helper@example.com')
        await H.click('#create'); await H.wait_for_timeout(300); await H.click('[data-tpl="home"]'); await H.wait_for_timeout(200)
        await H.click('.tpl-edit [data-back]'); await H.wait_for_timeout(200)
        check('What are you setting up?' in T(await H.inner_text('body')), 'Back returns to the choices')
        await H.click('[data-tpl="home"]'); await H.wait_for_timeout(200)
        await H.click('[data-create]'); await H.wait_for_timeout(5000)
        hs = next(f['id'] for f in G.FILES.values() if f['name'] == 'Home' and f['mime'] == G.SHEET and f['owner'] == 'helper@example.com')
        check(len(G.rows(hs, 'Locations')) == 7 + 13, f"home template: 7 places, 13 inside ({len(G.rows(hs, 'Locations'))})")
        check(not any(f['app'].get('stash') == 'group' and f['owner'] == 'helper@example.com' for f in G.FILES.values()), 'no group for a home')
        await h.close()
        # ---- start empty
        r_, R, rerr = await phone(b, 'ravi@example.com')
        await R.click('#create'); await R.wait_for_timeout(300); await R.click('[data-empty]'); await R.wait_for_timeout(300)
        await R.fill('.sheet input', 'Lake house'); await R.click('.sheet button.primary'); await R.wait_for_timeout(4000)
        check('#/setup' in R.url, 'empty start goes to the quick place setup as before')
        print('errors', errs + herr + rerr, [x for x in G.LOG if x[3] >= 400])
        await b.close()
    print('\nFAILURES:', FAILS or 'none'); sys.exit(1 if FAILS else 0)
asyncio.run(main())
